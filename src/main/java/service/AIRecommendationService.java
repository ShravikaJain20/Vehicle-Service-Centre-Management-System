    private String generateRuleBasedAnswer(String query, Vehicle vehicle) {
        String q = query.toLowerCase();

        if (q.contains("brake") || q.contains("spongy") || q.contains("squeak") || q.contains("grind")) {
            return "DIAGNOSTIC ADVICE: BRAKE SYSTEM\n\n" +
                   "- Spongy / Soft Pedal: Air trapped in hydraulic lines or moisture-contaminated brake fluid. Needs complete brake fluid flush (DOT 4) and line bleeding.\n" +
                   "- High-Pitched Squeal: Brake wear indicator shim touching rotor. Brake pads have reached minimum 2-3mm safety margin; replace immediately.\n" +
                   "- Grinding / Metal-on-Metal: Friction material completely exhausted. Rotor damage likely; requires new pads and rotor resurfacing/replacement.\n" +
                   "- Pedal Pulsation / Vibration: Warped brake rotors from excessive heat. Needs rotor runout measurement and skimming.";
        }

        if (q.contains("vibrat") || q.contains("shak") || q.contains("idle") || q.contains("pull")) {
            return "DIAGNOSTIC ADVICE: VIBRATION & STEERING STABILITY\n\n" +
                   "- Vibration at Idle: Worn engine mounts / hydraulic dampers, dirty throttle body, or spark plug misfire on one cylinder.\n" +
                   "- Vibration at 70-100 KM/H: Wheel imbalance. Requires dynamic 4-wheel balancing and rim bend inspection.\n" +
                   "- Vehicle Pulling to Left/Right: Wheel misalignment or uneven tyre pressure. Recommended computerized 4-wheel alignment and camber/toe calibration.";
        }

        if (q.contains("ac") || q.contains("cool") || q.contains("hvac") || q.contains("warm air")) {
            return "DIAGNOSTIC ADVICE: AIR CONDITIONING & CLIMATE CONTROL\n\n" +
                   "- Blowing Warm Air: Low refrigerant gas (R134a/R1234yf) due to micro-leak in condenser or evaporator core; or AC compressor clutch failure.\n" +
                   "- Foul / Musty Smell: Mould/bacterial buildup on evaporator fins. Needs foam disinfectant evaporator spray and new activated carbon cabin filter.\n" +
                   "- Weak Airflow: Clogged cabin air filter or malfunctioning blower motor resistor.";
        }

        if (q.contains("oil") || q.contains("synthetic") || q.contains("grade") || q.contains("viscosity")) {
            return "DIAGNOSTIC ADVICE: ENGINE LUBRICATION\n\n" +
                   "- Recommended Viscosity: Modern petrol/diesel engines typically require 0W-20, 5W-30, or 5W-40 Full Synthetic Oil (API SP / ACEA C3).\n" +
                   "- Replacement Interval: Full synthetic oil every 10,000 KM or 12 months; mineral/semi-synthetic every 5,000 KM.\n" +
                   "- Critical Rule: Always replace the oil filter alongside fresh oil. Never mix different oil viscosities or brands.";
        }

        if (q.contains("smoke") || q.contains("exhaust") || q.contains("black") || q.contains("blue") || q.contains("white")) {
            return "DIAGNOSTIC ADVICE: EXHAUST EMISSIONS\n\n" +
                   "- Blue Smoke: Engine oil entering combustion chamber (worn valve stem seals or piston rings). High oil consumption likely.\n" +
                   "- White Smoke (Sweet Smell): Coolant leaking into cylinder via blown head gasket. Risk of engine overheating and hydro-lock.\n" +
                   "- Black Smoke: Rich fuel mixture (excess fuel). Clogged air filter, leaky fuel injector, or faulty MAF/O2 sensor.";
        }

        if (q.contains("battery") || q.contains("start") || q.contains("crank")) {
            return "DIAGNOSTIC ADVICE: ELECTRICAL & STARTING\n\n" +
                   "- Slow Cranking: Low battery state of charge (below 12.4V), aged battery (> 3 years), or sulfated plates.\n" +
                   "- Rapid Clicking Noise: Battery lacks cranking amps to engage starter solenoid.\n" +
                   "- Battery Warning Light: Alternator charging circuit failure or snapped drive belt.";
        }

        // Generic intelligent response
        return "AUTOMOTIVE ASSISTANT RECOMMENDATION\n\n" +
               "Query: \"" + query + "\"\n\n" +
               "Assessment: For the reported symptom, we recommend performing a multi-point vehicle inspection:\n" +
               "1. Connect OBD-II diagnostic scanner to read active and pending DTC fault codes.\n" +
               "2. Inspect fluid levels (engine oil, brake fluid, coolant, steering fluid).\n" +
               "3. Verify battery terminal health and alternator voltage output (ideal 13.8V - 14.4V with engine running).\n" +
               "4. Road test to reproduce the symptom under load and braking.";
    }

    // -------------------------------------------------------------------------
    // Gemini HTTP API Client (Java 11+ java.net.http)
    // -------------------------------------------------------------------------

    private String callGeminiApi(String prompt, String apiKey) throws Exception {
        String model = DatabaseConfig.getAiModel();
        String url = "https://generativelanguage.googleapis.com/v1beta/models/" + model + ":generateContent?key=" + apiKey;

        String escapedPrompt = escapeJson(prompt);
        String requestBody = "{\"contents\":[{\"parts\":[{\"text\":\"" + escapedPrompt + "\"}]}],\"generationConfig\":{\"temperature\":0.2,\"maxOutputTokens\":800}}";

        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create(url))
                .header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(requestBody))
                .timeout(Duration.ofSeconds(15))
                .build();

        HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
        if (response.statusCode() == 200) {
            return extractTextFromGeminiJson(response.body());
        } else {
            System.err.println("Gemini API HTTP Error " + response.statusCode() + ": " + response.body());
            return null;
        }
    }

    private String buildPromptForRecommendation(Vehicle v, List<ServiceRecord> history) {
        return "You are an expert master automobile technician for a premium service centre. " +
               "Provide a structured, professional maintenance recommendation for: " +
               "Brand/Model: " + v.getBrand() + " " + v.getModel() + ", " +
               "Type: " + v.getVehicleType() + ", Year: " + v.getManufacturingYear() + ", " +
               "Odometer: " + v.getCurrentKm() + " KM, " +
               "Last Service Date: " + v.getLastServiceDate() + " at " + v.getLastServiceKm() + " KM. " +
               "Recommend priority service items, inspection points, and parts that should be checked or replaced. " +
               "Keep tone technical, concise, and structured.";
    }

    private String buildPromptForAssistant(String query, Vehicle v) {
        String vehContext = v != null ? ("Vehicle context: " + v.getBrand() + " " + v.getModel() + " (" + v.getCurrentKm() + " KM). ") : "";
        return "You are a professional automotive diagnostic assistant. " + vehContext +
               "Answer this maintenance or diagnostic inquiry with clear root-cause possibilities, mechanical explanations, and recommended troubleshooting steps: " +
               query;
    }

    private String extractTextFromGeminiJson(String json) {
        try {
            int textIdx = json.indexOf("\"text\": \"");
            if (textIdx != -1) {
                int start = textIdx + 9;
                int end = json.indexOf("\"", start);
                while (end != -1 && json.charAt(end - 1) == '\\') {
                    end = json.indexOf("\"", end + 1);
                }
                if (end != -1) {
                    String raw = json.substring(start, end);
                    return unescapeJson(raw);
                }
            }
        } catch (Exception ignored) {}
        return null;
    }

    private String escapeJson(String s) {
        return s.replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\n", "\\n")
                .replace("\r", "\\r")
                .replace("\t", "\\t");
    }

    private String unescapeJson(String s) {
        return s.replace("\\n", "\n")
                .replace("\\r", "\r")
                .replace("\\t", "\t")
                .replace("\\\"", "\"")
                .replace("\\\\", "\\");
    }

    private String truncate(String text, int maxLen) {
        if (text == null) return "";
        if (text.length() <= maxLen) return text;
        return text.substring(0, maxLen - 3) + "...";
    }
